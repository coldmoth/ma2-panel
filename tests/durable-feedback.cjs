'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const prefix = fs.readFileSync('tests/panel-v4.cjs', 'utf8').split('// Empty workspace:')[0];
const {context:c,ws,document} = new Function('require', prefix + '\nreturn {context,ws,document};')(require);
const timers=[]; c.setTimeout=fn=>{timers.push(fn);return timers.length;};
c.receive({status:{ma2:'logged_in',safety:{mode:'full'},features:{}}});
c.receive({config:{fixtures:[],groups:[],scenes:[],attrs:{}}});
c.send({a:'master',value:50});
const master=ws().sent.at(-1);
c.receive({request_id:master.request_id,a:'master',ok:false,err:'Пульт не ответил',outcome:'unknown'});
const errors=document.getElementById('errors');
assert.match(errors.textContent,/Общая яркость.*Пульт не ответил/);
assert.match(errors.children[0].getAttribute('title'),new RegExp(master.request_id));
for(const fn of timers.splice(0)) fn();
assert.equal(errors.hidden,false,'error survives notice timer');
c.feedback(null,true);
assert.match(errors.textContent,/Результат неизвестен/);
c.send({a:'dim',value:80});
const dim=ws().sent.at(-1);
c.receive({request_id:dim.request_id,a:'dim',ok:false,err:'Нет ответа',outcome:'partial'});
assert.equal(errors.children.length,2,'each failed operation remains separately dismissible');
c.send({a:'shows_list'}); ws().onclose(); c.connect();
assert.match(errors.textContent,/Пульт не ответил/);
assert.match(errors.textContent,/Связь прервана/);
const close=errors.all().find(n=>n.tagName==='BUTTON');close.click();
assert.doesNotMatch(errors.textContent,/Пульт не ответил/);
assert.match(errors.textContent,/Завершена только часть обработки/);
while(errors.children.length)errors.all().find(n=>n.tagName==='BUTTON').click();
assert.equal(errors.hidden,true);
console.log('durable feedback: timer, correlation, multiple failures, success, disconnect and explicit dismissal passed');

