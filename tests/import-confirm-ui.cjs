  status(); context.discardPending();
  context.receive({config:{fixtures:[],groups:[],scenes:[],presets:[],pages:{},attrs:{}}});
  context.go('start'); context.receive(ambiguity);
  assert.equal(findBtn('Применить выбор').disabled,true);
  let keep = page.all().filter(n=>n.tagName==='BUTTON' && n.textContent==='Оставить новый');
  keep[0].click();
  assert.equal(findBtn('Применить выбор').disabled,true,'every ambiguous item needs explicit selection');
  keep = page.all().filter(n=>n.tagName==='BUTTON' && n.textContent==='Оставить новый');
  keep[1].click();
  assert.equal(findBtn('Применить выбор').disabled,false,'all-new is a valid completed choice');
  findBtn('Применить выбор').click();
  assert.deepEqual(JSON.parse(JSON.stringify(sent().at(-1))),{a:'import_confirm_merge',request_token:'pending-token',choices:{'31':null,'32':null}});
  context.receive({ok:true,a:'import_confirm_merge',added:2,missing:2,total:4,no_id:['Без номера']});
  assert.match(document.getElementById('errors').textContent,/Без Fixture ID.*Без номера.*Дайте им Fixture ID/);
  context.receive(ambiguity);
  page.all().find(n=>n.tagName==='BUTTON' && n.textContent.startsWith('Объединить с #6')).click();
