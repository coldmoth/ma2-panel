  assert.equal(apply().disabled,true);
  resolveConfirmation({ok:false,json:async()=>({ok:false,err:'План изменился'})});
  await firstConfirm;
  assert.match(doc.getElementById('status').textContent,/План изменился/);
  assert.doesNotMatch(doc.getElementById('status').textContent,/Добавлено/);
