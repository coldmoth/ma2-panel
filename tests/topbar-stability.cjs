'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const prefix=fs.readFileSync('tests/panel-v4.cjs','utf8').split('// Empty workspace:')[0];
const {context:c,document,status,ws}=new Function('require',prefix+'\nreturn {context,document,status,ws};')(require);
status();
c.receive({config:{fixtures:[],groups:[],scenes:[],attrs:{}}});
const blackout=document.getElementById('blackout'),halt=document.getElementById('halt');
const power=blackout.children[0],stop=halt.children[0];
c.render();
assert.equal(blackout.children[0],power,'status refresh must preserve the target between pointerdown/up');
assert.equal(halt.children[0],stop,'halt target also stays attached');
const before=ws().sent.length;
blackout.click();assert(c.state.blackoutArm);assert.equal(ws().sent.length,before,'first press only arms');
const armedTarget=blackout.children[0];
status();assert.equal(blackout.children[0],armedTarget,'refresh preserves armed target');
blackout.click();assert.equal(ws().sent.filter(a=>a.a==='blackout').length,1,'second press still sends once');
status({halted:true});assert(blackout.disabled,'same real halt restriction');
console.log('topbar: stable pointer targets, original two-press confirmation and halt passed');
